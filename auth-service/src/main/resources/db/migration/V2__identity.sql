CREATE TABLE users(id UUID PRIMARY KEY,email VARCHAR(255) NOT NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,full_name VARCHAR(150) NOT NULL,phone VARCHAR(20),status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','LOCKED','DISABLED')),created_at TIMESTAMPTZ NOT NULL);
CREATE TABLE roles(name VARCHAR(30) PRIMARY KEY);
INSERT INTO roles VALUES ('ADMIN'),('CUSTOMER');
CREATE TABLE user_roles(user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,role VARCHAR(30) NOT NULL REFERENCES roles(name),PRIMARY KEY(user_id,role));
CREATE INDEX idx_user_roles_role ON user_roles(role);
